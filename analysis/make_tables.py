def render_all(res=None, app_res=None):
    res = cr.results() if res is None else res
    app_res = app.results() if app_res is None else app_res
    out = {"algebra_structure.tex": table_algebra_structure()}
    out.update({name: f(res) for name, f in TABLES.items()})
    out["application.tex"] = table_application(app_res)
    out["provenance.tex"] = table_provenance()
    return out


