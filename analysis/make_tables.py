def table_algebra_structure():
    """Irreducible components of V for the isotropic, cubic and hexagonal classes: dimension
    d_p, copies with their isotropic origin, block size n_p and the dimensions of the algebra
    (n_p^2) and of its elements with major symmetry (n_p (n_p + 1)/2). Computed from the
    embeddings of the package (origin = isotropic component on which each copy lies)."""
    iso = isotropic.algebra()
    origin_tex = {("H3", "3"): "H_3", ("H2", "2"): "H_2", ("H1", "s"): "H_1^{s}", ("H1", "r"): "H_1^{r}"}
    irrep_tex = {"H3": "H_3", "H2": "H_2", "H1": "H_1", "T1": "T_1", "T2": "T_2", "E": "E", "A2": "A_2",
                 "A1": "A_1", "B1": "B_1", "B2": "B_2", "E1": "E_1", "E2": "E_2"}
    classes = (("isotropic", iso), (r"cubic ($m\bar3m$)", cubic.algebra()),
               (r"hexagonal ($6/mmm$)", hexagonal.algebra()))
    lines = [HEADER, "\\begin{tabular}{llrlrrr}", "\\toprule",
             "Class & Irrep $p$ & $d_p$ & Copies (isotropic origin) & $n_p$ & $n_p^{2}$ & "
             "$\\tfrac12 n_p(n_p+1)$ \\\\", "\\midrule"]
    for ci, (cname, alg) in enumerate(classes):
        tot_v = 0
        for k, (p, copies, d) in enumerate(alg.irreps):
            orig = []
            for a in copies:
                E = alg.embedding(p, a)
                ov = {(q, b): float(np.sum((iso.embedding(q, b).T @ E) ** 2)) / d
                      for q, cc, _dd in iso.irreps for b in cc}
                (q, b), w = max(ov.items(), key=lambda t: t[1])
                assert abs(w - 1) < 1e-10, (p, a, w)
                orig.append(origin_tex[(q, b)])
            n = len(copies)
            tot_v += d * n
            lab = cname if k == 0 else ""
            lines.append(f"{lab} & ${irrep_tex[p]}$ & {d} & ${', '.join(orig)}$ & {n} & {n * n} & "
                         f"{n * (n + 1) // 2} \\\\")
        assert tot_v == 18
        lines.append(f" & total & & $\\textstyle\\sum_p d_p n_p = {tot_v}$ & & {alg.dimension} & "
                     f"{alg.symmetric_dimension} \\\\")
        if ci < len(classes) - 1:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_block_moduli(res):
    keys = list(cr.DATASETS)
    E = res["datasets"]
    lines = [HEADER, "\\begin{tabular}{l" + "r" * len(keys) + "}", "\\toprule",
             "Modulus (eV/\\AA) & " + " & ".join(E[k]["crystal"]["label"] for k in keys) + " \\\\",
             "\\midrule"]
    for m in cr.MODULI:
        lines.append(f"${MOD_TEX[m]}$ & " + " & ".join(
            num(E[k]["crystal"]["moduli"][m], f5, _u(E[k], f"moduli/{m}")) for k in keys) + " \\\\")
    lines.append("\\midrule")
    lines.append("Positive definite & " + " & ".join(
        "yes" if not E[k]["crystal"]["non_positive_blocks"]
        else "no (" + ", ".join(f"${p[0]}_{p[1]}$" for p in E[k]["crystal"]["non_positive_blocks"]) + ")"
        for k in keys) + " \\\\")
    lines.append("Condition number & " + " & ".join(
        num(E[k]["crystal"]["condition_number"], fcond, _u(E[k], "condition_number")) for k in keys) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_averages(res):
    lines = [HEADER, "\\begin{tabular}{llrrrrr}", "\\toprule",
             "Material & Estimate & " + " & ".join(f"${ISO_TEX[m]}$" for m in cr.ISO_MODULI) + " \\\\",
             "\\midrule"]
    keys = list(cr.DATASETS)
    for i, k in enumerate(keys):
        e = res["datasets"][k]
        for j, (name, lab) in enumerate((n, l) for n, l in EST.items() if n in e["averages"]):
            mat = e["crystal"]["label"] if j == 0 else ""
            lines.append(f"{mat} & {lab} & " + " & ".join(
                num(e["averages"][name]["moduli"][m], f5, _u(e, f"{name}/{m}")) for m in cr.ISO_MODULI) + " \\\\")
        if i < len(keys) - 1:
            lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_block_lengths(res):
    """Block lengths (A) of the three estimates, each with the classical C of the same
    estimate; spread max/min with two decimals."""
    lines = [HEADER, "\\begin{tabular}{llrrrrrr}", "\\toprule",
             "Material & Estimate & $\\ell_{3}$ & $\\ell_{2}$ & $\\ell_{1}^{-}$ & $\\ell_{1}^{+}$ & "
             "$\\ell_{\\max}/\\ell_{\\min}$ & $\\ell_{\\mathrm{LP}}$ \\\\",
             " & & (\\AA) & (\\AA) & (\\AA) & (\\AA) & & (\\AA) \\\\", "\\midrule"]
    for i, k in enumerate(cr.PD_SETS):
        e = res["datasets"][k]
        bl = e["block_lengths"]
        lines.append(f"{e['crystal']['label']} & crystal & -- & -- & -- & -- & -- & "
                     f"{num(bl['crystal']['lazar_po'], f3, _u(e, 'lengths/crystal/lazar_po'))} \\\\")
        for name, lab in EST.items():
            L = bl[name]["lengths"]
            vals = [("l3", L["H3"][0], f3), ("l2", L["H2"][0], f3), ("l1m", L["H1"][0], f3),
                    ("l1p", L["H1"][1], f3), ("max_over_min", bl[name]["max_over_min"], f2),
                    ("lazar_po", bl[name]["lazar_po"], f3)]
            lines.append(f" & {lab} & " + " & ".join(num(v, fmt, _u(e, f"lengths/{name}/{q}"))
                                                     for q, v, fmt in vals) + " \\\\")
        if i < len(cr.PD_SETS) - 1:
            lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def table_application(app_res):
    """Application table: Kroner's nu; large-grain limit of the scheme, 7 (8) terms;
    spread and Lazar-Po length of the Voigt block lengths with Kroner's C."""
    lines = [HEADER, "\\begin{tabular}{lrrrrr}", "\\toprule",
             "Material & $\\nu_{\\mathrm{K}}$ & $\\ell_{\\infty}$ (\\AA) & $\\rho/\\lvert\\Phi\\rvert$ & "
             "$\\ell_{\\max}/\\ell_{\\min}$ & $\\ell_{\\mathrm{LP}}$ (\\AA) \\\\", "\\midrule"]
    for key in app.MATERIALS:
        r = app_res["rows"][key]
        lim = r["limit"]
        lines.append(f"{r['label']} & {r['nu_kroner']:.4f} & {lim['7']['ell']:.3f} ({lim['8']['ell']:.3f}) & "
                     f"{lim['7']['residual']:.2f} ({lim['8']['residual']:.2f}) & "
                     f"{r['voigt_kroner_spread']:.2f} & {r['voigt_kroner_lazar_po']:.3f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


