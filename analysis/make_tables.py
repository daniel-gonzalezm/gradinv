def table_compliance(res):
    keys = cr.PD_SETS
    E = res["datasets"]
    lines = [HEADER, "\\begin{tabular}{l" + "r" * len(keys) + "}", "\\toprule",
             "Modulus (\\AA/eV) & " + " & ".join(E[k]["crystal"]["label"] for k in keys) + " \\\\",
             "\\midrule"]
    for m in cr.MODULI:
        lines.append(f"${INV_TEX[m]}$ & " + " & ".join(
            num(E[k]["crystal"]["compliance_moduli"][m], fc, _u(E[k], f"compliance/{m}")) for k in keys) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


