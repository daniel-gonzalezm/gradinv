def _latex_text(s):
    for a, b in (("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_")):
        s = s.replace(a, b)
    for pat, rep in _SYMBOLS:
        s = pat.sub(rep, s)
    return s


def _supplement(s):
    for pat, rep in _SUPPLEMENT_TEXT:
        s = pat.sub(rep, s)
    return s


def table_provenance():
    """Provenance of every input number (supplement), from analysis/data/provenance.csv.

    Its caption (with the label) is the macro \\ProvenanceCaption, defined in
    paper/supplement/S3_provenance.tex."""
    rows = list(csv.DictReader(PROVENANCE.open()))
    col = "".join(f">{{\\raggedright\\arraybackslash}}p{{{w}\\linewidth}}"
                  for w in ("0.04", "0.19", "0.07", "0.21", "0.08", "0.07", "0.16"))
    head = ["\\toprule", "ID & Quantity & Kind & Source & Location & Units & Rule of use \\\\", "\\midrule"]
    lines = [HEADER, "% needs the packages array, booktabs and longtable, and \\ProvenanceCaption",
             f"\\begin{{longtable}}{{@{{}}{col}@{{}}}}",
             "\\caption{\\ProvenanceCaption}\\\\", *head, "\\endfirsthead",
             *head, "\\endhead",
             "\\bottomrule", "\\endlastfoot"]
    for r in rows:
        units = _UNITS[r["units"]]
        cells = [r["id"], _latex_text(r["quantity"]), r["kind"], citations.cite(_latex_text(_supplement(r["source"]))),
                 _latex_text(_supplement(r["locator"])), units, citations.cite(_latex_text(_supplement(r["use_rule"])))]
        lines.append(" & ".join(cells) + " \\\\")
    lines.append("\\end{longtable}")
    return "\n".join(lines) + "\n"


