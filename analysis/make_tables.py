"""Generate the tables of the paper and of the supplement.

Writes analysis/tables/*.tex. Text: algebra_structure.tex, block_moduli.tex,
averages.tex, block_lengths.tex, application.tex. Supplement: compliance.tex,
provenance.tex. Each file is a booktabs fragment (tabular only; provenance.tex
is a longtable), with no float or caption, so the manuscript decides placement
and captions. Do not edit the .tex files by hand; the tests
tests/test_main_results.py, tests/test_application.py and tests/test_tables.py
fail if they are out of date.

Sources: algebra_structure from the package (gradinv.isotropic, cubic,
hexagonal); the cubic tables from analysis/cubic_results.py; application.tex
from analysis/application.py; provenance.tex from analysis/data/provenance.csv.

Digits: an entry is never shown with more significant figures than the rounding
of the published inputs supports (cubic_results.rounding_uncertainty: worst-case
linear effect of half a unit in the last printed digit of each input; for the
few entries that are far from linear, such as 1/m_E of Cu MEAM, it only sets
the order of magnitude, and those entries are flagged anyway). Entries
whose relative rounding uncertainty exceeds 1 per cent are marked with a dagger
(to be explained in the caption). The rule is in analysis/digits.py.

Run: python analysis/make_tables.py
"""
