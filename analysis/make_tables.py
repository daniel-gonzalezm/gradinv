# ------------------------------------------------------------------ number formatting
FLAG_REL = digits.FLAG_REL
_sig_figures = digits.significant_figures


def num(x, default, unc=0.0):
    """Math-mode entry: the default format, or fewer figures if the rounding of the inputs
    supports fewer (analysis/digits.py), with a dagger if the relative rounding
    uncertainty exceeds FLAG_REL."""
    s, flagged = digits.limit(x, default(x), unc)
    mark = MARK if flagged else ""
    if mark and "\\times" in s:
        s = "{" + s + "}"
    if x < 0 or "\\times" in s or mark:
        return f"${s}{mark}$"
    return s


def f5(x):
    return f"{x:.5f}"


def f3(x):
    return f"{x:.3f}"


def f2(x):
    return f"{x:.2f}"


def fc(x):
    """Compliance entries: 3 decimals; scientific with 3 figures from 1e3 on."""
    return digits.sci(x, 3) if abs(x) >= 1000 else f"{x:.3f}"


def fcond(x):
    """Condition numbers: three significant figures."""
    return digits.sci(x, 3) if x >= 1000 else f"{x:.3g}"


def _u(e, key):
    return e["rounding_uncertainty"].get(key, 0.0)


